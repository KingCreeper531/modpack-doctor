/// The frozen IPC surface: commands + typed events.
pub fn specta_builder() -> Builder<tauri::Wry> {
    use commands::*;
    Builder::<tauri::Wry>::new()
        // Contract types serialize and deserialize to the same shape; one TS type each.
        .disable_serde_phases()
        .commands(collect_commands![
            discover_instances,
            pick_and_add_folder,
            remove_manual_instance,
            pick_launcher_root,
            remove_launcher_root,
            pick_mrpack,
            scan_instance,
            list_log_sources,
            read_log_digest,
            set_watch,
            modrinth_identify,
            modrinth_find_updates,
            modrinth_projects,
            modrinth_project_versions,
            modrinth_resolve_mod_id,
            modrinth_icons,
            plan_work_order,
            execute_work_order,
            discard_work_order,
            list_backups,
            plan_undo,
            game_running,
            get_settings,
            set_settings,
            save_report,
            set_window_theme,
            check_update,
            install_update,
        ])
        .events(collect_events![
            model::ScanStarted,
            model::ScanProgress,
            model::CrashDetected,
            model::OpStatus,
            model::InstanceAdded,
            model::DropRejected,
        ])
        .typ::<error::AppError>()
        .typ::<model::JarStatus>()
        .typ::<model::LogBlock>()
}

pub const BINDINGS_PATH: &str = "../src/bindings.ts";

pub fn export_bindings(builder: &Builder<tauri::Wry>) -> Result<(), String> {
    builder
        .export(
            specta_typescript::Typescript::default()
                .header("// GENERATED by tauri-specta from src-tauri/src/model — do not edit.\n// @ts-nocheck\n"),
            BINDINGS_PATH,
        )
        .map_err(|e| e.to_string())
}

pub fn run() {
    let builder = specta_builder();

    #[cfg(debug_assertions)]
    if let Err(e) = export_bindings(&builder) {
        eprintln!("failed to export TypeScript bindings: {e}");
    }

    let result = tauri::Builder::default()
        // One app process (CONTRACTS.md invariant 14): registered first, so a second launch
        // exits right away and the running window comes to the front instead.
        .plugin(tauri_plugin_single_instance::init(|app, _args, _cwd| {
            if let Some(window) = app.get_webview_window("main") {
                let _ = window.unminimize();
                let _ = window.show();
                let _ = window.set_focus();
            }
        }))
        .plugin(tauri_plugin_dialog::init())
        .plugin(tauri_plugin_store::Builder::default().build())
        .plugin(tauri_plugin_opener::init())
        .plugin(tauri_plugin_notification::init())
        // tauri-plugin-updater is registered in M8, together with the signing pubkey.
        .invoke_handler(builder.invoke_handler())
        .setup(move |app| {
            builder.mount_events(app);
            // Settings (store plugin) + PathGuard app data root; managed before any command runs.
            let state = state::init(app.handle());
            let theme_pref = state.settings.get().theme;
            // Interrupted fix orders (crash, power loss): mark them before any order can run.
            fix::recover::recover_at_startup(&state);
            app.manage(state);
            // Theme the native title bar before the webview's first `set_window_theme` call:
            // the saved preference, else the system theme.
            if let Some(window) = app.get_webview_window("main") {
                let theme = match (theme_pref, window.theme()) {
                    (model::ThemePref::Dark, _) => model::ResolvedTheme::Dark,
                    (model::ThemePref::Light, _) => model::ResolvedTheme::Light,
                    (model::ThemePref::System, Ok(tauri::Theme::Light)) => model::ResolvedTheme::Light,
                    (model::ThemePref::System, _) => model::ResolvedTheme::Dark,
                };
                if let Err(e) = window_theme::apply(&window, theme) {
                    eprintln!("could not theme the title bar: {e}");
                }
            }
            Ok(())
        })
        .on_window_event(|window, event| {
            // Never close while fixes are being applied (CONTRACTS.md invariant 14).
            if let tauri::WindowEvent::CloseRequested { api, .. } = event {
                if fixes_running(window.app_handle()) {
                    api.prevent_close();
                    refuse_to_close(window.app_handle());
                }
            }
            // Files dropped on the window: `.mrpack`s are opened, everything else is reported
            // as `DropRejected` (CONTRACTS.md invariants 1 and 15). Paths never reach the UI.
            if let tauri::WindowEvent::DragDrop(tauri::DragDropEvent::Drop { paths, .. }) = event {
                commands::handle_drop(window.app_handle().clone(), paths.clone());
            }
        })
        .build(tauri::generate_context!());

    match result {
        Ok(app) => app.run(|handle, event| match event {
            tauri::RunEvent::ExitRequested { api, .. } if fixes_running(handle) => {
                api.prevent_exit();
                refuse_to_close(handle);
            }
            // Watchers are never persisted as running; stop their threads on the way out.
            tauri::RunEvent::Exit => {
                if let Some(state) = handle.try_state::<state::AppState>() {
                    state.watchers.stop_all();
                }
            }
            _ => {}
        }),
        Err(e) => {
            eprintln!("Modpack Doctor failed to start: {e}");
            std::process::exit(1);
        }
    }
}

/// True while a work order executes in any instance.
fn fixes_running<R: tauri::Runtime>(app: &tauri::AppHandle<R>) -> bool {
    app.try_state::<state::AppState>().is_some_and(|s| s.fixes.any_executing())
}

/// Native, non-blocking message explaining why the window stays open.
fn refuse_to_close<R: tauri::Runtime>(app: &tauri::AppHandle<R>) {
    use tauri_plugin_dialog::{DialogExt, MessageDialogKind};
    app.dialog()
        .message(
            "Modpack Doctor is applying fixes to a mods folder right now. Closing now could leave the folder half changed. \
             Wait until the fixes are finished, then close the app.",
        )
        .title("Fixes are being applied")
        .kind(MessageDialogKind::Warning)
        .show(|_| {});
}

